//! File-system adapter of the managed library: `<root>/staging` and `<root>/media` on the same volume.

use std::fs::{self, File, OpenOptions};
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};
use std::thread;
use std::time::Duration;

use super::hash::sha256_hex_file;
use crate::application::ports::{
    FileEntry, MediaEntry, MediaFs, Published, SourceHandle, SourceInfo, StagedFile,
};
use crate::domain::sound::{ContentHash, StorageKey};

const STAGING_DIR: &str = "staging";
const MEDIA_DIR: &str = "media";
/// Antivirus scanners and indexers can hold a new file for a moment on Windows, so the final rename is retried briefly.
const RENAME_ATTEMPTS: u32 = 3;
const RENAME_BACKOFF: Duration = Duration::from_millis(50);

pub struct OsMediaFs {
    staging: PathBuf,
    media: PathBuf,
}

impl OsMediaFs {
    /// Creates the two directories under `root` if needed. They are siblings, so a rename between them stays on one volume.
    pub fn open(root: &Path) -> io::Result<Self> {
        let staging = root.join(STAGING_DIR);
        let media = root.join(MEDIA_DIR);
        fs::create_dir_all(&staging)?;
        fs::create_dir_all(&media)?;
        Ok(Self { staging, media })
    }

    fn staging_path(&self, name: &str) -> io::Result<PathBuf> {
        // Staging names are generated by the application; refuse anything that is not a bare file name.
        let bare = !name.is_empty()
            && !name.contains(['/', '\\'])
            && name != "."
            && name != ".."
            && !name.contains('\0');
        if bare {
            Ok(self.staging.join(name))
        } else {
            Err(io::Error::from(io::ErrorKind::InvalidInput))
        }
    }

    fn media_path(&self, key: &StorageKey) -> PathBuf {
        key.components()
            .fold(self.media.clone(), |path, part| path.join(part))
    }
}

struct OsSource(File);

impl Read for OsSource {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        self.0.read(buffer)
    }
}

impl SourceHandle for OsSource {
    fn info(&self) -> io::Result<SourceInfo> {
        let metadata = self.0.metadata()?;
        Ok(SourceInfo {
            size: metadata.len(),
            modified: metadata.modified().ok(),
            is_regular_file: metadata.is_file(),
        })
    }
}

struct OsStaged(File);

impl Write for OsStaged {
    fn write(&mut self, buffer: &[u8]) -> io::Result<usize> {
        self.0.write(buffer)
    }

    fn flush(&mut self) -> io::Result<()> {
        self.0.flush()
    }
}

impl StagedFile for OsStaged {
    /// On macOS `File::sync_all` issues `F_FULLFSYNC`, which asks the drive to flush its own cache as well; on Windows it
    /// calls `FlushFileBuffers`.
    fn sync_all(&mut self) -> io::Result<()> {
        self.0.sync_all()
    }
}

impl MediaFs for OsMediaFs {
    fn open_source(&self, path: &Path) -> io::Result<Box<dyn SourceHandle>> {
        // A named pipe or device would block `open` forever, so a path that is not a regular file is refused first. The
        // opened handle is inspected again afterwards, which narrows (but cannot fully close) the check-then-open window.
        if !fs::metadata(path)?.is_file() {
            return Err(io::Error::from(io::ErrorKind::InvalidInput));
        }
        Ok(Box::new(OsSource(File::open(path)?)))
    }

    fn create_staging(&self, name: &str) -> io::Result<Box<dyn StagedFile>> {
        let path = self.staging_path(name)?;
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        Ok(Box::new(OsStaged(options.open(path)?)))
    }

    fn open_staged(&self, name: &str) -> io::Result<File> {
        File::open(self.staging_path(name)?)
    }

    fn remove_staged(&self, name: &str) -> io::Result<()> {
        match fs::remove_file(self.staging_path(name)?) {
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
            other => other,
        }
    }

    fn staging_entries(&self) -> io::Result<Vec<FileEntry>> {
        let mut entries = Vec::new();
        for entry in fs::read_dir(&self.staging)? {
            let entry = entry?;
            let metadata = entry.metadata()?;
            if !metadata.is_file() {
                continue;
            }
            let Ok(name) = entry.file_name().into_string() else {
                continue;
            };
            entries.push(FileEntry {
                name,
                size: metadata.len(),
                modified: metadata.modified().ok(),
            });
        }
        Ok(entries)
    }

    fn publish(&self, name: &str, key: &StorageKey) -> io::Result<Published> {
        let staged = self.staging_path(name)?;
        let target = self.media_path(key);
        let directory = target
            .parent()
            .ok_or_else(|| io::Error::from(io::ErrorKind::InvalidInput))?
            .to_path_buf();
        let shard_is_new = !directory.exists();
        fs::create_dir_all(&directory)?;

        if fs::symlink_metadata(&target).is_ok() {
            // A file is already at the key: an orphan of an interrupted import. Adopt it only if it holds exactly the
            // expected bytes; the hash is part of the key, so no other source of truth is needed.
            let expected = expected_hash(key)?;
            let is_regular = fs::symlink_metadata(&target)?.file_type().is_file();
            if is_regular && sha256_hex_file(&target)? == expected.as_str() {
                make_read_only(&target)?;
                fs::remove_file(&staged)?;
                return Ok(Published::AdoptedExisting);
            }
            return Err(io::Error::from(io::ErrorKind::AlreadyExists));
        }

        rename_with_retry(&staged, &target)?;
        // The staged data was synced before the move. Now make the move itself durable (see ADR 0007, "Durability").
        make_move_durable(&target, &directory)?;
        if shard_is_new {
            sync_directory(&self.media)?;
        }
        make_read_only(&target)?;
        Ok(Published::Moved)
    }

    fn media_entries(&self) -> io::Result<Vec<MediaEntry>> {
        let mut entries = Vec::new();
        for shard in fs::read_dir(&self.media)? {
            let shard = shard?;
            if !shard.metadata()?.is_dir() {
                continue;
            }
            let Ok(shard_name) = shard.file_name().into_string() else {
                continue;
            };
            for file in fs::read_dir(shard.path())? {
                let file = file?;
                let metadata = file.metadata()?;
                if !metadata.is_file() {
                    continue;
                }
                let Ok(file_name) = file.file_name().into_string() else {
                    continue;
                };
                entries.push(MediaEntry {
                    key: format!("{shard_name}/{file_name}"),
                    size: metadata.len(),
                    modified: metadata.modified().ok(),
                });
            }
        }
        Ok(entries)
    }

    fn media_size(&self, key: &StorageKey) -> io::Result<Option<u64>> {
        match fs::symlink_metadata(self.media_path(key)) {
            Ok(metadata) if metadata.file_type().is_file() => Ok(Some(metadata.len())),
            Ok(_) => Ok(None),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
            Err(error) => Err(error),
        }
    }

    fn open_media(&self, key: &StorageKey) -> io::Result<File> {
        let path = self.media_path(key);
        // Never follow a link planted inside the library.
        if !fs::symlink_metadata(&path)?.file_type().is_file() {
            return Err(io::Error::from(io::ErrorKind::InvalidInput));
        }
        File::open(path)
    }

    fn remove_media(&self, key: &StorageKey) -> io::Result<()> {
        let path = self.media_path(key);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_file() => {
                // Managed files are read-only; Windows refuses to delete a read-only file.
                let mut permissions = metadata.permissions();
                #[allow(clippy::permissions_set_readonly_false)]
                permissions.set_readonly(false);
                fs::set_permissions(&path, permissions)?;
                fs::remove_file(&path)
            }
            Ok(_) => Err(io::Error::from(io::ErrorKind::InvalidInput)),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(error) => Err(error),
        }
    }
}

fn expected_hash(key: &StorageKey) -> io::Result<ContentHash> {
    let file_name = key.components().last().unwrap_or_default();
    let stem = file_name
        .rsplit_once('.')
        .map(|(stem, _)| stem)
        .unwrap_or(file_name);
    ContentHash::parse(stem).map_err(|_| io::Error::from(io::ErrorKind::InvalidInput))
}

fn rename_with_retry(from: &Path, to: &Path) -> io::Result<()> {
    let mut attempt = 0;
    loop {
        match fs::rename(from, to) {
            Err(error)
                if error.kind() == io::ErrorKind::PermissionDenied
                    && attempt + 1 < RENAME_ATTEMPTS =>
            {
                attempt += 1;
                thread::sleep(RENAME_BACKOFF * attempt);
            }
            other => return other,
        }
    }
}

/// Flushes the published file and its directory entry as far as the platform allows (ADR 0007, "Durability").
///
/// - macOS: `File::sync_all` issues `fcntl(F_FULLFSYNC)` (confirmed in the Rust standard library), which asks the drive to
///   flush its own cache; plain `fsync` would not. The containing directory is flushed the same way.
/// - Linux and other Unix: `fsync` on the file and on the directory.
/// - Windows: directories cannot be opened through the standard library, so the file is reopened for writing and flushed
///   with `FlushFileBuffers`, which Microsoft documents as the way to commit to disk. `MOVEFILE_WRITE_THROUGH` is documented
///   only for moves done as copy-and-delete, so it is not relied on. NTFS journals the rename; behavior after a power loss
///   is not verified.
fn make_move_durable(file: &Path, directory: &Path) -> io::Result<()> {
    OpenOptions::new().write(true).open(file)?.sync_all()?;
    sync_directory(directory)
}

/// A file system that cannot flush a directory (some network, FAT-like or external volumes) cannot be made more durable
/// by failing the import, so that one case is tolerated; any other error is real.
#[cfg(unix)]
fn sync_directory(directory: &Path) -> io::Result<()> {
    match File::open(directory)?.sync_all() {
        Err(error)
            if matches!(
                error.kind(),
                io::ErrorKind::Unsupported | io::ErrorKind::InvalidInput
            ) =>
        {
            Ok(())
        }
        other => other,
    }
}

#[cfg(not(unix))]
fn sync_directory(_directory: &Path) -> io::Result<()> {
    Ok(())
}

fn make_read_only(path: &Path) -> io::Result<()> {
    let mut permissions = fs::metadata(path)?.permissions();
    permissions.set_readonly(true);
    fs::set_permissions(path, permissions)
}

/// Test helper: pretends a managed file was written `age` ago (managed files are read-only, so the flag is lifted briefly).
#[cfg(test)]
pub(crate) fn backdate(path: &Path, age: Duration) -> io::Result<()> {
    use std::time::SystemTime;
    let original = fs::metadata(path)?.permissions();
    let mut writable = original.clone();
    #[allow(clippy::permissions_set_readonly_false)]
    writable.set_readonly(false);
    fs::set_permissions(path, writable)?;
    OpenOptions::new()
        .write(true)
        .open(path)?
        .set_modified(SystemTime::now() - age)?;
    fs::set_permissions(path, original)
}
